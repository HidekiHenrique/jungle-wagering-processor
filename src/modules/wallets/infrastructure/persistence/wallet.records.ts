import { EntitySchema } from '@mikro-orm/core';
import { moneyColumn, timestampColumn } from '../../../../shared/infrastructure/database/column-types';

/** Row shapes of the wallets context. Persistence only: never leave the infrastructure layer. */
export class WalletRecord {
  id!: string;
  playerId!: string;
  currency!: string;
  balance!: string;
  version!: number;
  createdAt!: Date;
  updatedAt!: Date;
}

export const WalletRecordSchema = new EntitySchema<WalletRecord>({
  class: WalletRecord,
  tableName: 'wallets',
  properties: {
    id: { type: 'uuid', primary: true },
    playerId: { type: 'uuid' },
    currency: { type: 'string', columnType: 'char(3)' },
    balance: moneyColumn,
    version: { type: 'integer' },
    createdAt: timestampColumn,
    updatedAt: timestampColumn,
  },
});

export class LedgerEntryRecord {
  sequence?: string;
  id!: string;
  walletId!: string;
  transactionId!: string;
  direction!: string;
  amount!: string;
  currency!: string;
  balanceBefore!: string;
  balanceAfter!: string;
  createdAt!: Date;
}

export const LedgerEntryRecordSchema = new EntitySchema<LedgerEntryRecord>({
  class: LedgerEntryRecord,
  tableName: 'wallet_ledger_entries',
  properties: {
    // Generated by the database (identity); used as the stable, opaque cursor of the ledger.
    sequence: { type: 'bigint', persist: false, nullable: true },
    id: { type: 'uuid', primary: true },
    walletId: { type: 'uuid' },
    transactionId: { type: 'uuid' },
    direction: { type: 'string' },
    amount: moneyColumn,
    currency: { type: 'string', columnType: 'char(3)' },
    balanceBefore: moneyColumn,
    balanceAfter: moneyColumn,
    createdAt: timestampColumn,
  },
});
