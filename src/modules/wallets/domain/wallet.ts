import { DomainError, InvariantViolationError } from '../../../shared/domain/domain-error';
import { CurrencyMismatchError, Money } from '../../../shared/domain/money';
import { LedgerDirection } from './ledger-direction';
import { WalletLedgerEntry } from './wallet-ledger-entry';

export class InsufficientFundsError extends DomainError {
  readonly code = 'INSUFFICIENT_FUNDS';

  constructor(
    readonly walletId: string,
    readonly balance: Money,
    readonly requested: Money,
  ) {
    super(`Wallet ${walletId} has ${balance}, cannot debit ${requested}`);
  }
}

export class InvalidWalletError extends DomainError {
  readonly code = 'INVALID_WALLET';

  constructor(reason: string) {
    super(`Invalid wallet: ${reason}`);
  }
}

export interface WalletState {
  id: string;
  playerId: string;
  currency: string;
  balance: Money;
  version: number;
  createdAt: Date;
  updatedAt: Date;
}

/** Identifiers of the ledger entry a balance movement will produce (generated by the caller). */
export interface MovementProps {
  entryId: string;
  transactionId: string;
  money: Money;
  at: Date;
}

export interface OpenWalletProps {
  id: string;
  playerId: string;
  initialBalance: Money;
  at: Date;
  /** Required when initialBalance > 0: the OPENING transaction and its ledger entry. */
  opening?: { transactionId: string; entryId: string };
}

export interface OpenedWallet {
  wallet: Wallet;
  /** Present only when the initial balance is positive. */
  openingEntry?: WalletLedgerEntry;
}

/**
 * Aggregate root: the only way to change a balance.
 *
 * `debit` and `credit` return the ledger entry for the movement they just applied, so there is
 * no code path that changes the balance without producing its entry (and vice versa).
 * `version` starts at 1 and increases only when the balance changes: it is the optimistic
 * concurrency token checked by the repository (`UPDATE ... WHERE version = :expected`).
 */
export class Wallet {
  private constructor(
    readonly id: string,
    readonly playerId: string,
    readonly currency: string,
    private _balance: Money,
    private _version: number,
    readonly createdAt: Date,
    private _updatedAt: Date,
  ) {}

  /**
   * Opens a wallet already holding its initial balance, with version 1.
   * The initial credit is the OPENING movement: it gets a ledger entry, but does not bump the
   * version, because the wallet is born with that balance (challenge §9: version 1 after creation).
   */
  static open(props: OpenWalletProps): OpenedWallet {
    const { id, playerId, initialBalance, at, opening } = props;
    if (!id || !playerId) throw new InvalidWalletError('id and playerId are required');
    if (initialBalance.isNegative()) throw new InvalidWalletError('initial balance cannot be negative');

    const wallet = new Wallet(id, playerId, initialBalance.currency, initialBalance, 1, at, at);
    if (initialBalance.isZero()) return { wallet };

    if (!opening)
      throw new InvariantViolationError('a positive initial balance requires an OPENING transaction');
    const openingEntry = WalletLedgerEntry.create({
      id: opening.entryId,
      walletId: id,
      transactionId: opening.transactionId,
      direction: LedgerDirection.Credit,
      money: initialBalance,
      balanceBefore: Money.zero(initialBalance.currency),
      balanceAfter: initialBalance,
      createdAt: at,
    });
    return { wallet, openingEntry };
  }

  /** Rebuilds a persisted wallet. Does not re-validate transitions. */
  static rehydrate(state: WalletState): Wallet {
    return new Wallet(
      state.id,
      state.playerId,
      state.currency,
      state.balance,
      state.version,
      state.createdAt,
      state.updatedAt,
    );
  }

  get balance(): Money {
    return this._balance;
  }

  get version(): number {
    return this._version;
  }

  get updatedAt(): Date {
    return this._updatedAt;
  }

  canDebit(money: Money): boolean {
    this.assertSameCurrency(money);
    return !this._balance.isLessThan(money);
  }

  /** @throws InsufficientFundsError when the balance would become negative. */
  debit(props: MovementProps): WalletLedgerEntry {
    if (!this.canDebit(props.money)) throw new InsufficientFundsError(this.id, this._balance, props.money);
    return this.apply(LedgerDirection.Debit, props);
  }

  credit(props: MovementProps): WalletLedgerEntry {
    this.assertSameCurrency(props.money);
    return this.apply(LedgerDirection.Credit, props);
  }

  private apply(
    direction: LedgerDirection,
    { entryId, transactionId, money, at }: MovementProps,
  ): WalletLedgerEntry {
    const balanceBefore = this._balance;
    const balanceAfter =
      direction === LedgerDirection.Credit ? balanceBefore.add(money) : balanceBefore.subtract(money);

    // Built (and validated) before mutating: if the entry is invalid, the wallet is untouched.
    const entry = WalletLedgerEntry.create({
      id: entryId,
      walletId: this.id,
      transactionId,
      direction,
      money,
      balanceBefore,
      balanceAfter,
      createdAt: at,
    });

    this._balance = balanceAfter;
    this._version += 1;
    this._updatedAt = at;
    return entry;
  }

  private assertSameCurrency(money: Money): void {
    if (money.currency !== this.currency) throw new CurrencyMismatchError(this.currency, money.currency);
  }
}
